<?php
// Writes sql/schema.mysql.sql and sql/schema.sqlite.sql: the full schema after ALL migrations, for each dialect.
//   php tools/export_schema.php
// It replays lib/migrations.php against a recorder (nothing touches a real database).
declare(strict_types=1);

// Without an argument: run once per dialect (each run needs its own DB_DRIVER constant).
if (!in_array($argv[1] ?? '', ['mysql', 'sqlite'], true)) {
    foreach (['mysql', 'sqlite'] as $d) {
        passthru(escapeshellarg(PHP_BINARY) . ' ' . escapeshellarg(__FILE__) . ' ' . $d, $code);
        if ($code) exit($code);
    }
    exit(0);
}

$driver = $argv[1];
putenv("MLR_DB_DRIVER=$driver");
require __DIR__ . '/../config.php';
require __DIR__ . '/../lib/db.php';

/** A PDO stand-in that records statements instead of running them. */
final class RecorderPDO extends PDO
{
    public array $log = [];
    public function __construct() {}
    public function exec(string $statement): int|false { $this->log[] = trim(preg_replace('/^ {12}/m', '', $statement)); return 0; }
    public function query(string $query, ?int $fetchMode = null, mixed ...$args): PDOStatement|false { return new RecorderStmt(); }
    public function prepare(string $query, array $options = []): PDOStatement|false
    {
        if (stripos($query, 'INSERT INTO schema_version') !== false) return new RecorderStmt();
        return new RecorderStmt();
    }
    public function quote(string $string, int $type = PDO::PARAM_STR): string|false { return "'" . str_replace("'", "''", $string) . "'"; }
}
final class RecorderStmt extends PDOStatement
{
    public function execute(?array $params = null): bool { return true; }
    public function fetch(int $mode = PDO::FETCH_DEFAULT, int $cursorOrientation = PDO::FETCH_ORI_NEXT, int $cursorOffset = 0): mixed { return false; }
    public function fetchColumn(int $column = 0): mixed { return 0; }
    public function getIterator(): Iterator { return new ArrayIterator([]); }
}

$rec = new RecorderPDO();
run_migrations($rec);
$sql = "-- My Little Rockstar schema ($driver), after all migrations (version " . max(array_keys(migrations())) . ").\n"
     . "-- Generated by tools/export_schema.php — change lib/migrations.php instead of editing this file.\n"
     . "-- You don't need to import this: the game creates and upgrades its tables automatically.\n\n"
     . implode(";\n\n", array_filter($rec->log)) . ";\n";
file_put_contents(__DIR__ . "/../sql/schema.$driver.sql", $sql);
echo "wrote sql/schema.$driver.sql\n";
