<?php
// Writes sql/schema.mysql.sql and sql/schema.sqlite.sql from the single schema in lib/db.php.
//   php tools/export_schema.php
declare(strict_types=1);
require __DIR__ . '/../config.php';
require __DIR__ . '/../lib/db.php';
foreach (['mysql', 'sqlite'] as $driver) {
    $sql = "-- My Little Rockstar schema ($driver). Generated by tools/export_schema.php — edit lib/db.php instead.\n\n";
    foreach (schema_statements($driver) as $s) {
        if ($driver === 'mysql' && str_starts_with($s, 'CREATE INDEX')) $s = str_replace('IF NOT EXISTS ', '', $s);
        $sql .= preg_replace('/^ {8}/m', '', $s) . ";\n\n";
    }
    file_put_contents(__DIR__ . "/../sql/schema.$driver.sql", $sql);
    echo "wrote sql/schema.$driver.sql\n";
}
